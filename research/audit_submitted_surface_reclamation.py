def verify_manifest(manifest: dict[str, Any]) -> None:
    fresh = build_manifest()
    expected_surface = manifest.get("surface", {})
    fresh_surface = fresh["surface"]
    for key in (
        "contract_sha256",
        "expanded_regular_files",
        "current_bytes",
        "current_global_headroom_bytes",
    ):
        if expected_surface.get(key) != fresh_surface[key]:
            raise AuditError(f"manifest surface verification failed at {key}")
    expected_files = expected_surface.get("files")
    if expected_files != fresh_surface["files"]:
        raise AuditError("manifest file records differ from current surface")

    plan = manifest.get("reclamation_plan", {})
    target_data = (ROOT / TARGET).read_bytes()
    candidate = apply_ranges(target_data, plan.get("ranges", []))
    removed = [
        target_data[item["start_byte"] : item["end_byte_exclusive"]]
        for item in plan.get("ranges", [])
    ]
    reconstructed = reconstruct_original(
        candidate, plan.get("ranges", []), removed, len(target_data)
    )
    if sha256(candidate) != plan.get("candidate_sha256"):
        raise AuditError("manifest candidate hash mismatch")
    if reconstructed != target_data:
        raise AuditError("manifest reverse reconstruction mismatch")
    if manifest.get("decision") != fresh["decision"]:
        raise AuditError("manifest decision differs from fresh audit")


def checked_output_path(value: str) -> Path:
    path = (ROOT / value).resolve() if not Path(value).is_absolute() else Path(value).resolve()
    if path.parent != RESEARCH_ROOT:
        raise AuditError("outputs must be direct children of research/")
    return path


def controls_text(manifest: dict[str, Any]) -> str:
    lines = ["submitted-surface reclamation positive controls"]
    lines.extend(
        f"PASS {item['name']}: {item['detail']}"
        for item in manifest["positive_controls"]
    )
    lines.append(
        "PASS submitted_files_read_only: dry run used in-memory byte strings only"
    )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Audit a reversible, research-only submitted-source deletion plan."
    )
    parser.add_argument("--output", help="write a manifest under research/")
    parser.add_argument(
        "--controls-output", help="write positive-control output under research/"
    )
    parser.add_argument("--verify", help="verify an existing manifest")
    args = parser.parse_args()

    try:
        if args.verify:
            path = checked_output_path(args.verify)
            manifest = json.loads(path.read_text())
            verify_manifest(manifest)
            print(
                "verified: files=142 bytes=2984121 "
                f"reclaimed={manifest['reclamation_plan']['reclaimed_bytes']} "
                f"decision={manifest['decision']['status']}"
            )
            return 0

        manifest = build_manifest()
        if args.output:
            output = checked_output_path(args.output)
            output.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
        if args.controls_output:
            controls_output = checked_output_path(args.controls_output)
            controls_output.write_text(controls_text(manifest))
        print(
            f"surface={manifest['surface']['expanded_regular_files']} "
            f"bytes={manifest['surface']['current_bytes']} "
            f"ranges={manifest['reclamation_plan']['range_count']} "
            f"reclaimed={manifest['reclamation_plan']['reclaimed_bytes']} "
            f"decision={manifest['decision']['status']}"
        )
        return 0
    except (AuditError, OSError, json.JSONDecodeError, KeyError, ValueError) as error:
        print(f"audit failed closed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
