def canonical_surface_digest(records: list[dict[str, Any]]) -> str:
    logical = [
        {"path": item["path"], "size": item["bytes"], "sha256": item["sha256"]}
        for item in records
    ]
    encoded = json.dumps(
        logical, sort_keys=True, separators=(",", ":"), ensure_ascii=False
    ).encode("utf-8") + b"\n"
    return sha256(encoded)


def validate_surface_summary(summary: dict[str, int | str]) -> None:
    expected: dict[str, int | str] = {
        "expanded_regular_files": EXPECTED_FILE_COUNT,
        "current_bytes": EXPECTED_TOTAL_BYTES,
        "current_global_headroom_bytes": EXPECTED_GLOBAL_HEADROOM,
        "target_bytes": EXPECTED_TARGET_BYTES,
        "target_headroom_bytes": EXPECTED_TARGET_HEADROOM,
        "canonical_logical_manifest_sha256": EXPECTED_CANONICAL_MANIFEST_SHA256,
    }
    for key, value in expected.items():
        if summary.get(key) != value:
            raise AuditError(f"submitted surface control mismatch: {key}")


def build_surface_manifest() -> tuple[list[dict[str, Any]], bytes, list[str]]:
    contract, contract_raw = base_contract()
    rules = contract["editablePaths"]
    base_paths = base_surface_paths(rules)
    working_paths, matched_by = working_surface_paths(rules)
    if base_paths != working_paths:
        raise AuditError("required-base and working submitted path sets differ")
    prior = prior_payload_records()
    if set(prior) != set(working_paths):
        raise AuditError("ranked-payload manifest path set differs from reconstructed surface")

    records: list[dict[str, Any]] = []
    total = 0
    for path in working_paths:
        data = (ROOT / path).read_bytes()
        size = len(data)
        digest = sha256(data)
        total += size
        prior_item = prior[path]
        if prior_item["size"] != size or prior_item["sha256"] != digest:
            raise AuditError(f"ranked-payload cross-check failed for {path}")
        record = {
            "path": path,
            "sha256": digest,
            "bytes": size,
            "per_file_limit_bytes": MAX_FILE_BYTES,
            "per_file_headroom_bytes": MAX_FILE_BYTES - size,
            "editable_path_rule": matched_by[path],
            **source_classification(path, data),
        }
        if record["per_file_headroom_bytes"] < 0:
            raise AuditError(f"per-file cap exceeded by {path}")
        records.append(record)

    target_record = next(item for item in records if item["path"] == TARGET)
    validate_surface_summary(
        {
            "expanded_regular_files": len(records),
            "current_bytes": total,
            "current_global_headroom_bytes": MAX_TOTAL_BYTES - total,
            "target_bytes": target_record["bytes"],
            "target_headroom_bytes": target_record["per_file_headroom_bytes"],
            "canonical_logical_manifest_sha256": canonical_surface_digest(records),
        }
    )
    return records, contract_raw, rules


def build_reclamation_plan() -> dict[str, Any]:
    data = (ROOT / TARGET).read_bytes()
    spans = scan_swift(data)
    code = masked_code(data, spans)
    location_tokens = [
        {
            "token": match.group().decode("ascii"),
            "byte": match.start(),
            "line": line_number(data, match.start()),
        }
        for match in SOURCE_LOCATION_PATTERN.finditer(code)
    ]
    if location_tokens:
        raise AuditError(
            "source-location-sensitive tokens make target comment deletion ambiguous"
        )
    ranges, exclusions = whole_line_comment_blocks(data, spans)
    candidate = apply_ranges(data, ranges)
    removed = [
        data[item["start_byte"] : item["end_byte_exclusive"]] for item in ranges
    ]
    reconstructed = reconstruct_original(candidate, ranges, removed, len(data))
    if reconstructed != data:
        raise AuditError("reverse reconstruction hash check failed")
    if data.count(b"\n") != candidate.count(b"\n"):
        raise AuditError("candidate changed physical line count")

    removed_bytes = sum(item["bytes"] for item in ranges)
    return {
        "paths": [TARGET],
        "path_count": 1,
        "class": "lexer_proven_swift_whole_line_comments_only",
        "ranges": ranges,
        "range_count": len(ranges),
        "excluded_comment_sites": exclusions,
        "source_location_tokens_outside_strings_and_comments": location_tokens,
        "original_bytes": len(data),
        "original_sha256": sha256(data),
        "candidate_bytes": len(candidate),
        "candidate_sha256": sha256(candidate),
        "reclaimed_bytes": removed_bytes,
        "newline_count_preserved": data.count(b"\n"),
        "nondeleted_bytes_remain_in_order": True,
        "reverse_reconstruction_matches_original": True,
        "reverse_reconstruction_sha256": sha256(reconstructed),
        "writes_submitted_files": False,
        "dry_run_medium": "in_memory_only",
    }


def synthetic_ranges(data: bytes) -> list[dict[str, Any]]:
    spans = scan_swift(data)
    code = masked_code(data, spans)
    if SOURCE_LOCATION_PATTERN.search(code):
        return []
    return whole_line_comment_blocks(data, spans)[0]


def expect_rejected(name: str, condition: bool, detail: str) -> dict[str, Any]:
    if not condition:
        raise AuditError(f"positive control failed: {name}")
    return {"name": name, "status": "PASS", "detail": detail}


def run_positive_controls(plan: dict[str, Any]) -> list[dict[str, Any]]:
    controls: list[dict[str, Any]] = []

    string_fixture = b'let a = "// ordinary"\nlet b = #"// raw"#\n'
    controls.append(
        expect_rejected(
            "comment_like_sequences_inside_swift_strings",
            synthetic_ranges(string_fixture) == [],
            "ordinary and raw string contents produced zero deletion ranges",
        )
    )

    embedded_fixture = (
        b'let source = #"""\n'
        b'// embedded Metal comment\n'
        b'kernel void active_kernel() {}\n'
        b'"""#\n'
    )
    controls.append(
        expect_rejected(
            "embedded_metal_source_range",
            synthetic_ranges(embedded_fixture) == [],
            "comment-like Metal text inside a Swift raw multiline string was excluded",
        )
    )

    license_fixture = (
        b"// Copyright 2026 Example\n"
        b"// Licensed under the Example License\n"
        b"let value = 1\n"
    )
    controls.append(
        expect_rejected(
            "required_license_block",
            synthetic_ranges(license_fixture) == [],
            "the complete adjacent license comment block was excluded",
        )
    )

    active_fixture = (
        b'let activeRegistry = ProcessInfo.processInfo.environment['
        b'"ACTIVE_SELECTOR"] != "0"\n'
        b"// removable explanation\n"
    )
    active_ranges = synthetic_ranges(active_fixture)
    token_offset = active_fixture.index(b"ACTIVE_SELECTOR")
    token_covered = any(
        item["start_byte"] <= token_offset < item["end_byte_exclusive"]
        for item in active_ranges
    )
    controls.append(
        expect_rejected(
            "active_selector_registry_token",
            len(active_ranges) == 1 and not token_covered,
            "the code token remained outside the sole comment-only deletion range",
        )
    )

    macro_fixture = b"#define VALUE \\\n// unsafe continuation site\n1\n"
    macro_comment = macro_fixture.index(b"//")
    macro_hazard = (
        b"#define" in macro_fixture
        and b"\\\n" in macro_fixture
        and macro_comment > macro_fixture.index(b"\\\n")
    )
    controls.append(
        expect_rejected(
            "c_cpp_macro_line_continuation_hazard",
            macro_hazard,
            "C/C++/Metal files are excluded; the fixture's continued macro is rejected",
        )
    )

    first = plan["ranges"][0]
    target_data = (ROOT / TARGET).read_bytes()
    corrupted = copy.deepcopy(first)
    corrupted["removed_sha256"] = "0" * 64
    hash_rejected = False
    try:
        apply_ranges(target_data, [corrupted])
    except AuditError:
        hash_rejected = True
    controls.append(
        expect_rejected(
            "corrupted_expected_byte_hash",
            hash_rejected,
            "a modified deletion receipt failed closed before dry-run application",
        )
    )

    corrupted_summary: dict[str, int | str] = {
        "expanded_regular_files": EXPECTED_FILE_COUNT + 1,
        "current_bytes": EXPECTED_TOTAL_BYTES,
        "current_global_headroom_bytes": EXPECTED_GLOBAL_HEADROOM,
        "target_bytes": EXPECTED_TARGET_BYTES,
        "target_headroom_bytes": EXPECTED_TARGET_HEADROOM,
        "canonical_logical_manifest_sha256": EXPECTED_CANONICAL_MANIFEST_SHA256,
    }
    count_rejected = False
    try:
        validate_surface_summary(corrupted_summary)
    except AuditError:
        count_rejected = True
    controls.append(
        expect_rejected(
            "corrupted_surface_manifest",
            count_rejected,
            "a changed file count failed the same exact-surface validator used by the audit",
        )
    )
    return controls


