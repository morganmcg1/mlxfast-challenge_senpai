class AuditError(RuntimeError):
    pass


@dataclass(frozen=True)
class Span:
    kind: str
    start: int
    end: int
    hashes: int = 0
    multiline: bool = False


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def git_bytes(*args: str) -> bytes:
    process = subprocess.run(
        ["git", *args],
        cwd=ROOT,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if process.returncode != 0:
        message = process.stderr.decode("utf-8", errors="replace").strip()
        raise AuditError(f"git {' '.join(args)} failed: {message}")
    return process.stdout


def validate_relative_path(value: str) -> None:
    path = Path(value)
    if (
        not value
        or path.is_absolute()
        or "\\" in value
        or "\x00" in value
        or any(part in ("", ".", "..") for part in path.parts)
    ):
        raise AuditError(f"unsafe editable path: {value!r}")


def base_contract() -> tuple[dict[str, Any], bytes]:
    raw = git_bytes("show", f"{BASE_SHA}:benchmark.json")
    if sha256(raw) != EXPECTED_CONTRACT_SHA256:
        raise AuditError("required-base benchmark.json hash drifted")
    current = (ROOT / "benchmark.json").read_bytes()
    if current != raw:
        raise AuditError("working benchmark.json differs from the required base")
    contract = json.loads(raw)
    rules = contract.get("editablePaths")
    if not isinstance(rules, list) or not rules:
        raise AuditError("required-base benchmark.json has no editablePaths")
    for rule in rules:
        if not isinstance(rule, str):
            raise AuditError("editablePaths includes a non-string entry")
        validate_relative_path(rule)
    return contract, raw


def base_surface_paths(rules: list[str]) -> list[str]:
    paths: set[str] = set()
    for rule in rules:
        raw = git_bytes("ls-tree", "-r", "--name-only", "-z", BASE_SHA, "--", rule)
        for item in raw.split(b"\0"):
            if not item:
                continue
            path = item.decode("utf-8")
            validate_relative_path(path)
            paths.add(path)
    return sorted(paths)


def working_surface_paths(rules: list[str]) -> tuple[list[str], dict[str, str]]:
    paths: set[str] = set()
    matched_by: dict[str, str] = {}
    for rule in rules:
        absolute = ROOT / rule
        if absolute.is_symlink():
            raise AuditError(f"editable path is a symlink: {rule}")
        if absolute.is_file():
            candidates = [absolute]
        elif absolute.is_dir():
            candidates = [path for path in absolute.rglob("*") if path.is_file()]
        else:
            candidates = []
        for absolute_path in candidates:
            mode = absolute_path.lstat().st_mode
            if stat.S_ISLNK(mode) or not stat.S_ISREG(mode):
                raise AuditError(f"non-regular submitted path: {absolute_path}")
            relative = absolute_path.relative_to(ROOT).as_posix()
            if relative in paths and matched_by[relative] != rule:
                raise AuditError(
                    f"submitted path matched multiple rules: {relative}"
                )
            paths.add(relative)
            matched_by[relative] = rule
    return sorted(paths), matched_by


def scan_swift(data: bytes) -> list[Span]:
    spans: list[Span] = []
    length = len(data)
    index = 0
    while index < length:
        if data.startswith(b"//", index):
            end = data.find(b"\n", index + 2)
            if end < 0:
                end = length
            spans.append(Span("line_comment", index, end))
            index = end
            continue
        if data.startswith(b"/*", index):
            start = index
            index += 2
            depth = 1
            while index < length and depth:
                if data.startswith(b"/*", index):
                    depth += 1
                    index += 2
                elif data.startswith(b"*/", index):
                    depth -= 1
                    index += 2
                else:
                    index += 1
            if depth:
                raise AuditError("unterminated nested Swift block comment")
            spans.append(Span("block_comment", start, index))
            continue

        hashes = 0
        quote_index = index
        if data[index] == 0x23:
            while quote_index < length and data[quote_index] == 0x23:
                hashes += 1
                quote_index += 1
        if quote_index < length and data[quote_index] == 0x22:
            multiline = data.startswith(b'"""', quote_index)
            quote_length = 3 if multiline else 1
            opening_start = index if hashes else quote_index
            body = quote_index + quote_length
            closing = b'"' * quote_length + b"#" * hashes
            cursor = body
            while cursor < length:
                if data.startswith(closing, cursor):
                    end = cursor + len(closing)
                    spans.append(
                        Span(
                            "string",
                            opening_start,
                            end,
                            hashes=hashes,
                            multiline=multiline,
                        )
                    )
                    index = end
                    break
                if hashes == 0 and data[cursor] == 0x5C:
                    cursor += 2
                    continue
                if not multiline and data[cursor] in (0x0A, 0x0D):
                    raise AuditError("newline in a single-line Swift string")
                cursor += 1
            else:
                raise AuditError("unterminated Swift string")
            continue
        index += 1
    return spans


def line_number(data: bytes, offset: int) -> int:
    return data.count(b"\n", 0, offset) + 1


def masked_code(data: bytes, spans: list[Span]) -> bytes:
    masked = bytearray(data)
    for span in spans:
        for index in range(span.start, span.end):
            if masked[index] not in (0x0A, 0x0D):
                masked[index] = 0x20
    return bytes(masked)


def whole_line_comment_blocks(
    data: bytes, spans: list[Span]
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    candidates: list[dict[str, Any]] = []
    exclusions: list[dict[str, Any]] = []
    whole_lines: list[tuple[Span, int, int, int]] = []
    for span in spans:
        if span.kind != "line_comment":
            continue
        start = data.rfind(b"\n", 0, span.start) + 1
        prefix = data[start:span.start]
        if prefix.strip(b" \t"):
            exclusions.append(
                {
                    "line": line_number(data, span.start),
                    "reason": "trailing_or_inline_comment",
                }
            )
            continue
        end = span.end
        if end > start and data[end - 1 : end] == b"\r":
            end -= 1
        if end <= start:
            continue
        whole_lines.append((span, start, end, line_number(data, start)))

    blocked_lines: set[int] = set()
    block: list[tuple[Span, int, int, int]] = []
    blocks: list[list[tuple[Span, int, int, int]]] = []
    for item in whole_lines:
        if block and item[3] != block[-1][3] + 1:
            blocks.append(block)
            block = []
        block.append(item)
    if block:
        blocks.append(block)

    for comment_block in blocks:
        combined = b"\n".join(
            data[item[0].start : item[0].end].lower() for item in comment_block
        )
        markers = [
            marker.decode("ascii")
            for marker in LICENSE_OR_TOOLING_MARKERS
            if marker in combined
        ]
        if markers:
            for item in comment_block:
                blocked_lines.add(item[3])
            exclusions.append(
                {
                    "start_line": comment_block[0][3],
                    "end_line": comment_block[-1][3],
                    "reason": "required_license_or_tooling_directive_block",
                    "markers": markers,
                }
            )

    for _span, start, end, line in whole_lines:
        if line in blocked_lines:
            continue
        removed = data[start:end]
        candidates.append(
            {
                "start_byte": start,
                "end_byte_exclusive": end,
                "start_line": line,
                "end_line": line,
                "class": "swift_whole_line_comment_body_preserve_newline",
                "bytes": len(removed),
                "removed_sha256": sha256(removed),
                "proof_id": "swift-comment-token-preserve-line-map-v1",
            }
        )
    return candidates, exclusions


def apply_ranges(data: bytes, ranges: list[dict[str, Any]]) -> bytes:
    output: list[bytes] = []
    cursor = 0
    for item in ranges:
        start = item["start_byte"]
        end = item["end_byte_exclusive"]
        if not (cursor <= start < end <= len(data)):
            raise AuditError("range ordering or bounds failure")
        removed = data[start:end]
        if len(removed) != item["bytes"]:
            raise AuditError("range byte count mismatch")
        if sha256(removed) != item["removed_sha256"]:
            raise AuditError("range removed-byte hash mismatch")
        output.append(data[cursor:start])
        cursor = end
    output.append(data[cursor:])
    return b"".join(output)


def reconstruct_original(
    candidate: bytes, ranges: list[dict[str, Any]], removed: list[bytes], original_size: int
) -> bytes:
    output: list[bytes] = []
    original_cursor = 0
    candidate_cursor = 0
    for item, deleted in zip(ranges, removed, strict=True):
        gap_length = item["start_byte"] - original_cursor
        output.append(candidate[candidate_cursor : candidate_cursor + gap_length])
        candidate_cursor += gap_length
        output.append(deleted)
        original_cursor = item["end_byte_exclusive"]
    tail_length = original_size - original_cursor
    output.append(candidate[candidate_cursor : candidate_cursor + tail_length])
    candidate_cursor += tail_length
    if candidate_cursor != len(candidate):
        raise AuditError("reverse reconstruction did not consume candidate")
    return b"".join(output)


def language_for(path: str) -> str:
    suffix = Path(path).suffix
    return {
        ".swift": "swift",
        ".cpp": "c++",
        ".h": "c++/metal-header",
        ".metal": "metal",
    }.get(suffix, "unknown")


def swift_contains_embedded_source(data: bytes) -> bool:
    spans = scan_swift(data)
    markers = (b"threadgroup_position_in_grid", b"metal::", b"kernel void")
    return any(
        span.kind == "string"
        and any(marker in data[span.start : span.end] for marker in markers)
        for span in spans
    )


def source_classification(path: str, data: bytes) -> dict[str, Any]:
    generated = "/mlx-generated/" in f"/{path}"
    ordinary = Path(path).suffix in (".swift", ".cpp") and not generated
    runtime_embedded = generated
    if path.endswith(".swift"):
        runtime_embedded = swift_contains_embedded_source(data)
    if generated:
        source_kind = "generated_runtime_embedded_source"
        exclusion = "runtime-effective generated C++ source; synchronized twin required"
    elif runtime_embedded:
        source_kind = "ordinary_compiled_source_with_runtime_embedded_text"
        exclusion = "only lexer-proven outer Swift comments may be considered"
    elif path.endswith((".metal", ".h")):
        source_kind = "runtime_effective_kernel_source"
        exclusion = "AOT/JIT/kernel twin source excluded from this plan"
    else:
        source_kind = "ordinary_compiled_source"
        exclusion = None
    return {
        "language": language_for(path),
        "generated": generated,
        "runtime_embedded": runtime_embedded,
        "ordinary_compiled_source": ordinary,
        "source_kind": source_kind,
        "generated_or_kernel_exclusion": exclusion,
    }


